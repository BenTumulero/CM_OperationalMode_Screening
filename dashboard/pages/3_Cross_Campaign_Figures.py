"""Cross-Campaign Figures gallery.

Renders the comparison figures exported by the notebooks in
`Cross_Campaign_Comparison/` (SVG/PNG/HTML files, including the
`export/` subfolder).
"""

from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

DASHBOARD_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = DASHBOARD_DIR.parent
if str(DASHBOARD_DIR) not in sys.path:
    sys.path.insert(0, str(DASHBOARD_DIR))

from views.figure_gallery import render_gallery

st.set_page_config(page_title="Cross-Campaign Figures — AnimaKinetica", layout="wide")

render_gallery(
    root_dir=REPO_ROOT / "Cross_Campaign_Comparison",
    title="Cross-Campaign Figures",
    description=(
        "Comparison figures generated by the notebooks in "
        "`Cross_Campaign_Comparison/`. Re-run a notebook to regenerate its "
        "exports."
    ),
    extensions=(".html",),
    layout="tabs",
)
