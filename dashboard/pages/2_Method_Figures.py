"""Method Figures gallery.

Renders the publication-focused figures exported by the notebooks in
`Method Figures/` (SVG/PNG/HTML files at the top level of that folder).
"""

from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

DASHBOARD_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = DASHBOARD_DIR.parent
if str(DASHBOARD_DIR) not in sys.path:
    sys.path.insert(0, str(DASHBOARD_DIR))

from views.figure_gallery import render_gallery

st.set_page_config(page_title="Method Figures — AnimaKinetica", layout="wide")

render_gallery(
    root_dir=REPO_ROOT / "Method Figures",
    title="Method Figures",
    description=(
        "Publication-focused figures generated by the notebooks in "
        "`Method Figures/`. Re-run a notebook to regenerate its exports."
    ),
    extensions=(".html",),
    layout="tabs",
)
