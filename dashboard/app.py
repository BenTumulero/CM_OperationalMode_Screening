"""AnimaKinetica Data Dashboard — Streamlit entry point (landing page).

Run from the repository root:

    streamlit run dashboard/app.py

The dashboard is a standalone consumer of the `animakinetica` package
(public API only). It is a multipage app:

    pages/1_Simulation_Explorer.py     — browse & inspect single simulation files
    pages/2_Method_Figures.py         — gallery of Method Figures exports
    pages/3_Cross_Campaign_Figures.py — gallery of Cross-Campaign exports
"""

from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

# Make `sources` / `views` importable from pages as well.
DASHBOARD_DIR = Path(__file__).resolve().parent
REPO_ROOT = DASHBOARD_DIR.parent
if str(DASHBOARD_DIR) not in sys.path:
    sys.path.insert(0, str(DASHBOARD_DIR))

st.set_page_config(page_title="AnimaKinetica Dashboard", layout="wide")


def main() -> None:
    st.title("AnimaKinetica Data Dashboard")
    st.markdown(
        "Welcome! Use the navigation in the sidebar to switch between the "
        "dashboard sections."
    )

    st.markdown(
        """
        | Section | What it shows |
        |---|---|
        | **Simulation Explorer** | Browse exported simulation files (pickle/Excel), inspect batches, kinetics, gas/pH control, stoichiometry, process metrics, parameters, and optimization results. |
        | **Method Figures** | Publication-focused figures generated by the notebooks in `Method Figures/`. |
        | **Cross-Campaign Figures** | Comparison figures generated by the notebooks in `Cross_Campaign_Comparison/`. |
        """
    )

    st.caption(
        "Simulation Explorer loads `SimulationData` pickles exported with "
        "`sim.data.save(...)` or `save_pickle(...)`. Figure galleries render "
        "the SVG/PNG/HTML exports written by the Method Figures and "
        "Cross-Campaign notebooks."
    )



if __name__ == "__main__":
    main()
